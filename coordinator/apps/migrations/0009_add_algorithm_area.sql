CREATE TABLE IF NOT EXISTS algorithm_areas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    map_name VARCHAR(128) NOT NULL UNIQUE COMMENT '地图名称',
    area_data JSON NOT NULL COMMENT '算法区域列表(存储 algorithmAreas 数组)',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='地图算法区域配置表';